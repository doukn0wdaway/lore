package lore

import (
	"fmt"
	"os"
	"strings"
)

const indexHeader = "<!-- generated by lore index — do not edit -->"

// RenderIndex builds INDEX.md: the zone list with tldrs. ADRs are not listed —
// their number grows without bound; they reach the agent through `lore show`.
func RenderIndex(zones []*Zone) string {
	var b strings.Builder
	b.WriteString(indexHeader + "\n# lore index\n\nZones (open with `lore show <id>`):\n\n")
	if len(zones) == 0 {
		b.WriteString("_No zones yet._\n")
		return b.String()
	}
	for _, z := range zones {
		tldr := strings.TrimSpace(z.TLDR)
		if tldr == "" {
			tldr = "_(no tldr)_"
		}
		fmt.Fprintf(&b, "- **%s** — %s\n", z.Key(), tldr)
	}
	return b.String()
}

// WriteIndex regenerates INDEX.md and reports whether it changed.
func (p *Project) WriteIndex() (bool, error) {
	zones, err := p.LoadZones()
	if err != nil {
		return false, err
	}
	want := RenderIndex(zones)
	path := p.Path("INDEX.md")
	if have, err := os.ReadFile(path); err == nil && string(have) == want {
		return false, nil
	}
	return true, os.WriteFile(path, []byte(want), 0o644)
}
